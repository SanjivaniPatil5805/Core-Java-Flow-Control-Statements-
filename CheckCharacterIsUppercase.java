package com.practice;

public class CheckCharacterIsUppercase {

	public static void main(String[] args) {
		
		char ch = 'N';
		
		if(ch >= 'A' && ch <= 'Z') {
			
			System.out.println("Character is Uppercase.");
			
		}
		else {
			
			System.out.println("Character is not Uppercase.");
			
		}
	}
}
